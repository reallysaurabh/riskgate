"""Render benchmarks/results/tau2_report.md from tau2_{retail,airline}_results.json (+ effect validation)."""
from __future__ import annotations

import json
from pathlib import Path

RES = Path(__file__).resolve().parents[1] / "results"


def pct(x, d=1):
    if x is None or isinstance(x, str):
        return "—"
    return f"{100 * x:.{d}f}%"


def f2(x):
    if x is None or isinstance(x, str) or (isinstance(x, float) and x != x):
        return "—"
    return f"{x:.2f}"


def load(dom):
    p = RES / f"tau2_{dom}_results.json"
    return json.loads(p.read_text()) if p.exists() else None


def rs(r, alpha, m):
    try:
        return r[f"a{alpha}"]["resplits"][m]
    except KeyError:
        return None


def main() -> None:
    L = ["# RiskGate on real LLM agents: tau2-bench (retail, airline)", "",
         "*Generated by `benchmarks/tau2/report.py`. Agents: the eight 2026 frontier-model runs published on the tau2-bench "
         "leaderboard (S3 bucket `sierra-tau-bench-public`) and the four 2025 runs in the tau2-bench repository. Every write "
         "was replayed in the real tau2 environment (0 replay mismatches). Trajectories are model outputs subject to their "
         "providers' terms; only aggregates and short excerpts are reproduced here.*", ""]
    val = RES / "tau2_effect_validation.json"
    for dom in ("retail", "airline"):
        R = load(dom)
        if R is None:
            continue
        L += [f"## {dom.capitalize()}", ""]
        # 1. the problem
        L += ["### The problem: wrong database writes by real agents", "",
              "| Agent | Year | Writes | Wrong writes (strict) | Upper bound | Wrong writes right after an explicit customer \"yes\" |",
              "|---|---|---|---|---|---|"]
        for m, v in R["models"].items():
            n_unsafe = round(v["unsafe_pooled"] * v["n"])
            L.append(f"| {m} | {v['year']} | {v['n']} | {n_unsafe} ({pct(v['unsafe_pooled'])}) | {pct(v['unsafe_upper'])} | "
                     f"{v['unsafe_confirmed']} of {n_unsafe} |")
        L += ["", "Strict: the write matches no gold write (tau2's own comparison, or the same canonical effect) and the run's final "
              "database differs from the gold database. Upper bound: every write that matches no gold write.", ""]
        # 2. per agent
        L += ["### RiskGate per agent (policy mode: calibrated on the agent's runs of half the tasks, tested on the rest)", "",
              "Mean over 200 random task re-splits (the quantity conformal risk control bounds); *task-avg* = share of a task's "
              "decisions, averaged over tasks (the guaranteed quantity).", "",
              "| Agent | Base unsafe (task-avg) | AUROC gate / committee | α=5%: unsafe, ask | α=10%: unsafe, ask | committee α=10%: unsafe, ask |",
              "|---|---|---|---|---|---|"]
        for m, v in R["models"].items():
            a = R["auroc"][m]
            base = v.get("unsafe_taskavg", v["unsafe_pooled"])
            r5, r10, c10 = rs(v, 5, "riskgate"), rs(v, 10, "riskgate"), rs(v, 10, "committee")
            n_cal = v["a5"]["n_groups"] // 2
            cell5 = f"{pct(r5['unsafe_mean'])}, {pct(r5['ask_mean'], 0)}" if n_cal >= 19 else "infeasible (<19 calibration tasks)"
            L.append(f"| {m} | {pct(base)} | {f2(a['mass'])} / {f2(a.get('committee'))} | {cell5} | "
                     f"{pct(r10['unsafe_mean'])}, {pct(r10['ask_mean'], 0)} | {pct(c10['unsafe_mean'])}, {pct(c10['ask_mean'], 0)} |")
        # 3. baselines pooled 2026
        for key, title in (("2026_a10", "pooled 2026 agents, α = 10%"), ("2026_a5", "pooled 2026 agents, α = 5%")):
            P = R["pooled"].get(key)
            if not P:
                continue
            L += ["", f"### Methods compared ({title}; groups = tasks, {P['n_groups']} tasks, {P['n_decisions']} writes)", "",
                  "| Method | Fixed split: unsafe (task-avg), unsafe per write, ask, safe-auto | Re-splits: unsafe mean ± sd, ask, splits > α |",
                  "|---|---|---|"]
            for mname, r in P["fixed_split"].items():
                q = P["resplits"].get(mname)
                rtxt = f"{pct(q['unsafe_mean'])} ± {pct(q['unsafe_sd'])}, {pct(q['ask_mean'], 0)}, {pct(q['frac_above_alpha'], 0)}" if q else "—"
                L.append(f"| {mname} | {pct(r['unsafe'])}, {pct(r['unsafe_pooled'])}, {pct(r['ask'], 0)}, "
                         f"{pct(r['safe_auto'], 0)} | {rtxt} |")
        # 4. upgrade
        U = R.get("upgrade", {})
        if U:
            L += ["", "### Agent upgrade: calibrate on the 2025 agents, deploy on the 2026 agents (held-out tasks)", "",
                  "| α | Calibrated on 2025 runs: unsafe mean ± sd, ask, splits > α | "
                  "Recalibrated on 2026 runs: unsafe, ask, splits > α |", "|---|---|---|"]
            for a, v in U.items():
                o, n = v["calibrated_on_2025"], v["recalibrated_on_2026"]
                L.append(f"| {a[1:]}% | {pct(o['unsafe_mean'])} ± {pct(o['unsafe_sd'])}, {pct(o['ask_mean'], 0)}, {pct(o['frac_above_alpha'], 0)} | "
                         f"{pct(n['unsafe_mean'])} ± {pct(n['unsafe_sd'])}, {pct(n['ask_mean'], 0)}, {pct(n['frac_above_alpha'], 0)} |")
        # 5. tools
        L += ["", "### By tool (2026 agents)", "", "| Tool | Writes | Unsafe | AUROC gate | AUROC committee |", "|---|---|---|---|---|"]
        for t, v in R["by_tool_2026"].items():
            L.append(f"| `{t}` | {v['n']} | {pct(v['unsafe'])} | {f2(v['auroc'])} | {f2(v.get('auroc_committee'))} |")
        p9 = R.get("p9", {})
        L += ["", f"Library check (P9): `Gate.calibrate(groups=...)` on the fixed 2026 split returns λ̂ = {p9.get('lambda_library')} "
              f"(harness: {p9.get('lambda_harness')}; α = {p9.get('alpha')}, {p9.get('n_groups')} task groups, {p9.get('n_decisions')} writes).", ""]
        # 6. examples
        if R.get("examples"):
            L += ["### Examples (2026 agents, pooled α = 10% threshold)", ""]
            for e in R["examples"][:6]:
                gold = "; ".join(f"{g['name']}({json.dumps(g['args'])[:160]})" for g in e["gold"][:2]) or "(no write expected)"
                L += [f"**{e['kind']}** — {e['model']}, task {e['task']}, score {e['score']:.2f}", "",
                      f"> Customer (first message): {e['first_user'][:300]}", "",
                      "```text", f"agent : {e['call']['name']}({json.dumps(e['call']['args'])[:220]})", f"gold  : {gold}",
                      f"most plausible readings: {e['top_hypotheses']}", "```", ""]
    if val.exists():
        v = json.loads(val.read_text())
        L += ["## Consequence-model check against the real tau2 environment", "",
              "For sampled 2026 writes, the run was replayed in a fresh tau2 environment; the agent's call, each gold write and "
              "each executable alternative reading were executed on copies of the database.", "",
              "| Domain | Decisions | Calls | Tool errors | Pairs compared | "
              "Canonical key ⇔ same database | key equal, DB differs | key differs, DB equal |",
              "|---|---|---|---|---|---|---|---|"]
        for dom in ("retail", "airline"):
            g = lambda k, dom=dom: v.get(f"{dom}:{k}", 0)  # noqa: E731
            if g("decisions"):
                L.append(f"| {dom} | {g('decisions')} | {g('calls')} | {g('errors')} | {g('pairs')} | "
                         f"{pct(g('agree') / max(1, g('pairs')))} | {g('key_eq_db_neq')} | {g('key_neq_db_eq')} |")
        L.append("")
    L += ["## How to read this (and what it does not show)", "",
          "* **Offline replay.** Each logged write is one decision with the conversation so far as context. What would have happened "
          "after an ASK (a human reviewing the write) is not observed; a certified write is assumed executed exactly as logged.",
          "* **Labels** are tau2's gold actions and final-database check, not human judgement. Strict labels miss wrong writes in runs "
          "that still passed; the upper bound counts equivalent alternatives as wrong.",
          "* **What an LLM-free gate cannot see.** Many wrong writes are *upstream* errors: the agent misinformed the customer, who then "
          "explicitly asked for the wrong action (\"the reason is: ordered by mistake\"). No verifier grounded only in the conversation "
          "and database can flag those; they bound the achievable discrimination.",
          "* **Validity vs efficiency.** Conformal risk control bounds the unsafe rate whatever the score; the score (hypothesis provider) "
          "only decides how many writes must be asked to stay within α. The primary gate uses transparent lexical evidence with weights "
          "frozen on the 2025 runs; the committee variant (hypotheses = other agents' runs on the same task) was added after the primary "
          "evaluation as an exploratory analysis and needs extra agent calls in deployment.",
          "* **Sample size.** CRC can certify at level α only with at least ⌈1/α⌉ − 1 calibration groups; with 50 airline tasks, α = 5% "
          "is infeasible per agent.", ""]
    (RES / "tau2_report.md").write_text("\n".join(L))
    print("wrote", RES / "tau2_report.md")


if __name__ == "__main__":
    main()
