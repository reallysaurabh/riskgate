"""Render docs/results.md from examples/results/*.json (so the numbers in the docs are never typed by hand).

    cd examples && python report.py
"""
from __future__ import annotations

import json
import math
import shutil
from pathlib import Path

HERE = Path(__file__).resolve().parent
RES = HERE / "results"
OUT = HERE.parent / "docs" / "results.md"
ASSETS = HERE.parent / "docs" / "assets"
GH = "https://github.com/reallysaurabh/riskgate/blob/main/"
DOMS = [("cstr_reactor", "Chemical reactor (CSTR)"), ("k8s_incident", "Kubernetes incident (SRE agent)"),
        ("refunds_agent", "Refunds (support agent)")]
SHORT = {"cstr_reactor": "reactor", "k8s_incident": "Kubernetes", "refunds_agent": "refunds"}
METHODS = [("no_checker", "No checker"), ("twin_gate", "Twin gate (binary, top-1)"), ("top1_crc", "Top-1 + CRC"),
           ("riskgate", "**riskgate**"), ("riskgate_hp", "**riskgate (LTT, δ′ = 0.1)**"),
           ("riskgate_probe", "**riskgate + probe**")]


def pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def num(x) -> str:
    if isinstance(x, str):
        return "∞" if "inf" in x.lower() else x
    if x is None:
        return "–"
    return "∞" if not math.isfinite(x) else f"{x:.3g}"


def main() -> None:
    R = {d: json.loads((RES / f"{d}_results.json").read_text()) for d, _ in DOMS if (RES / f"{d}_results.json").exists()}
    A = json.loads((RES / "ablations.json").read_text()) if (RES / "ablations.json").exists() else {}
    L: list[str] = []
    w = L.append
    w("# Results (simulated domains)\n")
    w("> [!IMPORTANT]\n> Everything on this page comes from **simulated** domains with **scripted** (LLM-like) agents. The "
      "simulators use realistic parameters, the truth simulator always differs from the gate's model, and labels are "
      "counterfactual outcomes for every candidate. Real-LLM evaluations are planned. This page is generated by "
      f"[`examples/report.py`]({GH}examples/report.py) from `examples/results/*.json`.\n")
    w("## Setup\n")
    w("| | Chemical reactor (CSTR) | Kubernetes incident | Refunds |\n|---|---|---|---|")
    w("| consequence model | first-principles twin, unaware of plant mismatch | Erlang-C queueing twin, Postgres limits "
      "| SQLite transactional dry-run |")
    w("| latent state (hypotheses) | fault type × magnitude (19) | incident cause × magnitude (13) | order/item intent × unsynced chargeback |")
    w("| spec | 340 K ≤ T ≤ 362 K for 30 min | p95 ≤ 800 ms and errors ≤ 2% each minute | no improper payout |")
    sizes = " | ".join(f"{R[d]['n_cal']} / {R[d]['nominal']['riskgate']['n']} / {R[d].get('shift', {}).get('riskgate', {}).get('n', '–')}"
                       for d, _ in DOMS if d in R)
    w(f"| calibration / test / shift episodes | {sizes} |\n")
    w("All methods see identical episodes and identical agent proposals. α = 5%, δ = 5%, policy mode; 30% of the "
      "calibration episodes set the plausible-set threshold τ, the rest the acceptance threshold(s).\n")
    w("| Method | What it does |\n|---|---|")
    w("| No checker | execute the agent's first choice |")
    w("| Twin gate | certify if the margin under the single best-fitting hypothesis is ≥ 0 (today's twin-gated agents) |")
    w("| Top-1 + CRC | the same score, with a threshold calibrated by conformal risk control |")
    w("| riskgate | worst margin over all plausible hypotheses, CRC threshold (expectation guarantee) |")
    w("| riskgate (LTT) | the same score with the high-probability guarantee, P(risk ≤ α) ≥ 0.9 |")
    w("| riskgate + probe | two-stage probing (λ₁ at 0.6α, λ₂ at 0.4α over all episodes of its split) |\n")

    w("## 1. Validity: mean over random re-splits\n")
    w("Conformal risk control bounds the risk **in expectation over calibration sets**. The right check is therefore the "
      "mean test unsafe rate over random re-splits of the pooled calibration and test episodes.\n")
    w("| Domain | Method | re-splits | unsafe (mean ± sd) | ask (mean) | splits above α |\n|---|---|---|---|---|---|")
    for d, title in DOMS:
        if d not in R:
            continue
        for m, label in [("riskgate", "riskgate"), ("riskgate_hp", "riskgate (LTT)"), ("riskgate_probe", "riskgate + probe"),
                         ("top1_crc", "Top-1 + CRC")]:
            v = R[d].get("resplits", {}).get(m)
            if v:
                w(f"| {title} | {label} | {v['n']} | {pct(v['unsafe_mean'])} ± {pct(v['unsafe_sd'])} | {pct(v['ask_mean'])} | "
                  f"{pct(v['frac_above_alpha'])} |")
    w("\n![validity over re-splits](assets/validity_resplits.png)\n")
    w("\n\"Splits above α\" includes test-sampling noise (a few hundred test episodes per split), so it is not expected "
      "to be zero even for a valid method.\n")

    w("## 2. One fixed split (nominal and shifted test episodes)\n")
    w("Brackets: 95% Wilson intervals (test sampling only). *Ask* includes rejects. Under shift the guarantee does not apply.\n")
    for d, title in DOMS:
        if d not in R:
            continue
        r = R[d]
        w(f"### {title}\n")
        w("| Method | unsafe (nominal) | ask | safe execution | probe | unsafe (shift) | ask (shift) |\n|---|---|---|---|---|---|---|")
        for m, label in METHODS:
            v, s = r["nominal"].get(m), r.get("shift", {}).get(m)
            if not v:
                continue
            w(f"| {label} | {pct(v['unsafe'])} [{100 * v['unsafe_ci'][0]:.1f}, {100 * v['unsafe_ci'][1]:.1f}] | {pct(v['ask'])} | "
              f"{pct(v['safe_execution'])} | {pct(v['probe'])} | {pct(s['unsafe']) if s else '–'} | {pct(s['ask']) if s else '–'} |")
        c = r["calibration"]
        w(f"\nCalibrated: τ = {num(c['tau'])}, mean plausible hypotheses = {c['mean_plausible']:.2f}, λ̂ = {num(c['lambda'])}, "
          f"λ̂ (LTT) = {num(c.get('lambda_hp'))}, λ̂ (top-1) = {num(c['lambda_top1'])}, probing λ₁/λ₂ = "
          f"{num(c['lambda_probe'][0])} / {num(c['lambda_probe'][1])} ({c['n_probe']} probed calibration episodes).\n")

    w("![methods](assets/methods_all_domains.png)\n")

    w("## 3. Target levels (riskgate, fixed split)\n")
    alphas = sorted({s["alpha"] for d in R for s in R[d]["alpha_sweep"]})
    w("| Domain | " + " | ".join(f"α = {a:.2f}" for a in alphas) + " |\n|---|" + "---|" * len(alphas))
    for d, title in DOMS:
        if d not in R:
            continue
        by = {s["alpha"]: s for s in R[d]["alpha_sweep"]}
        w(f"| {title}: unsafe | " + " | ".join(pct(by[a]["unsafe"]) if a in by else "–" for a in alphas) + " |")
        w("| ask | " + " | ".join(pct(by[a]["ask"]) if a in by else "–" for a in alphas) + " |")
    w("\n![alpha sweep](assets/alpha_sweep_all_domains.png)\n")

    w("## 4. What the numbers say\n")
    rg = {d: R[d] for d in R}
    if "cstr_reactor" in rg:
        c = rg["cstr_reactor"]
        w("1. **The agent alone is often wrong.** Its first choice is unsafe in "
          + ", ".join(f"{pct(rg[d]['nominal']['no_checker']['unsafe'])} ({SHORT[d]})" for d, _ in DOMS if d in rg)
          + " of test episodes. A binary twin gate removes most of that but still lets through "
          + ", ".join(pct(rg[d]['nominal']['twin_gate']['unsafe']) for d, _ in DOMS if d in rg) + ".")
        hp = {d: rg[d]["resplits"].get("riskgate_hp") for d in rg}
        base = {d: rg[d]["resplits"].get("riskgate") for d in rg}
        w("2. **riskgate meets the target on average** in all three domains (table 1), and so do its high-probability and "
          "probing variants. The high-probability variant also *narrows* the spread of the realised risk: in the "
          f"Kubernetes domain its re-split sd is {pct(hp['k8s_incident']['unsafe_sd'])} vs {pct(base['k8s_incident']['unsafe_sd'])} "
          f"at the same ask rate ({pct(hp['k8s_incident']['ask_mean'])} vs {pct(base['k8s_incident']['ask_mean'])}), and no "
          "split exceeded α in any domain; in the reactor it pays for this with many more asks "
          f"({pct(hp['cstr_reactor']['ask_mean'])} vs {pct(base['cstr_reactor']['ask_mean'])}). Top-1 + CRC averages "
          f"{pct(rg['cstr_reactor']['resplits']['top1_crc']['unsafe_mean'])} in the reactor, within re-split noise of α, "
          "while asking about almost everything.")
        w(f"3. **One split of the reactor lands above α** ({pct(c['nominal']['riskgate']['unsafe'])} on the fixed split). "
          "This is the variability an expectation guarantee allows, amplified by a *cliff*: one action, lowering the "
          "setpoint by 5 K (usually the agent's second choice), has a robust score of about −5.03 in many episodes, always "
          "set by the same worst-case hypothesis (a thermocouple reading 10 K high), and it is unsafe in about half of "
          "them. Whether the calibrated threshold lands just below or just above −5.03 depends on a handful of "
          "calibration episodes. The high-probability guarantee "
          f"({pct(c['nominal']['riskgate_hp']['unsafe'])} on this split) and probing "
          f"({pct(c['nominal']['riskgate_probe']['unsafe'])}) reduce the problem. If you need the bound for *your* "
          "artefact, use `guarantee=\"high_probability\"`.")
    if "refunds_agent" in rg and "cstr_reactor" in rg and "k8s_incident" in rg:
        f, c, k = rg["refunds_agent"], rg["cstr_reactor"], rg["k8s_incident"]
        w(f"4. **Calibrating around the single best diagnosis is vacuous when misdiagnoses matter**: top-1 + CRC asks in "
          f"{pct(f['nominal']['top1_crc']['ask'])} of refund and {pct(c['nominal']['top1_crc']['ask'])} of reactor episodes "
          f"(the certification-rate ceiling, Proposition 1 of the paper). In the Kubernetes domain, where a wrong diagnosis "
          f"rarely changes which actions are safe, it is competitive ({pct(k['nominal']['top1_crc']['unsafe'])} unsafe, "
          f"{pct(k['nominal']['top1_crc']['ask'])} asks vs riskgate's {pct(k['nominal']['riskgate']['unsafe'])} and "
          f"{pct(k['nominal']['riskgate']['ask'])}). We report this honestly: the robust score matters most where "
          "diagnosis is ambiguous in a safety-relevant way.")
        w(f"5. **Probing turns some \"I can't tell\" into safe action**: asks fall from {pct(f['nominal']['riskgate']['ask'])} "
          f"to {pct(f['nominal']['riskgate_probe']['ask'])} (refunds), {pct(k['nominal']['riskgate']['ask'])} to "
          f"{pct(k['nominal']['riskgate_probe']['ask'])} (Kubernetes) and {pct(c['nominal']['riskgate']['ask'])} to "
          f"{pct(c['nominal']['riskgate_probe']['ask'])} (reactor), using risk budget that single-stage gating left unused.")
        w(f"6. **Under shift** riskgate degrades but stays well below the twin gate: {pct(c['shift']['riskgate']['unsafe'])} vs "
          f"{pct(c['shift']['twin_gate']['unsafe'])} (reactor, including an unseen fault type), "
          f"{pct(k['shift']['riskgate']['unsafe'])} vs {pct(k['shift']['twin_gate']['unsafe'])} (Kubernetes), "
          f"{pct(f['shift']['riskgate']['unsafe'])} vs {pct(f['shift']['twin_gate']['unsafe'])} (refunds), mostly by asking more.")
    w("")

    if A:
        w("## 5. Ablations (refunds and Kubernetes, fixed split)\n")
        doms = [d for d in ("refunds_agent", "k8s_incident") if d in A]
        w("| Variant | " + " | ".join(f"{dict(DOMS)[d].split(' (')[0]}: unsafe | ask" for d in doms) + " |")
        w("|---|" + "---|---|" * len(doms))
        rows = [("policy mode (default)", "A1_policy"), ("agnostic mode", "A1_agnostic"),
                ("policy mode, doer swapped after calibration", "A2_policy_doer_swap"),
                ("agnostic mode, doer swapped", "A2_agnostic_doer_swap"), ("δ = 0.01", "A3_delta_0.01"),
                ("δ = 0.2", "A3_delta_0.2"), ("δ = 0.5", "A3_delta_0.5"), ("high-probability (LTT)", "A5_high_probability"),
                ("probing, ρ = 0.4", "A6_probe_share_0.4"), ("probing, ρ = 0.6", "A6_probe_share_0.6"),
                ("probing, ρ = 0.8", "A6_probe_share_0.8")]
        for label, key in rows:
            cells = []
            for d in doms:
                v = A[d].get(key, {})
                cells += [pct(v["unsafe"]) if "unsafe" in v else "–", pct(v["ask"]) if "ask" in v else "–"]
            w(f"| {label} | " + " | ".join(cells) + " |")
        for n in (150, 300, 600, 1200):
            cells = []
            for d in doms:
                v = A[d].get(f"A4_n_{n}")
                cells += ([f"{pct(v['unsafe_mean'])} ± {pct(v['unsafe_sd'])}", pct(v["ask_mean"])] if v else ["–", "–"])
            w(f"| n_cal = {n} (10 re-splits, mean ± sd) | " + " | ".join(cells) + " |")
        k = A.get("k8s_incident", {})
        if k:
            w(f"\n- **Doer swap.** Re-ordering the Kubernetes agent's proposals at random after calibration raises the policy-mode "
              f"risk from {pct(k['A1_policy']['unsafe'])} to {pct(k['A2_policy_doer_swap']['unsafe'])} (the edge of α); agnostic "
              f"mode goes from {pct(k['A1_agnostic']['unsafe'])} to {pct(k['A2_agnostic_doer_swap']['unsafe'])}. This is why "
              "`doer_id` is part of the policy-mode fingerprint.")
        w("- **δ** trades plausible-set size against emptiness: asks are lowest around δ = 0.05.")
        w("- **Calibration size** leaves the mean below α but shrinks the spread across re-splits.")
        w("- **High-probability vs expectation** pick the same threshold on this split in both domains: their risk curves "
          "jump from well below to well above α between neighbouring thresholds. Across re-splits the high-probability "
          "threshold is stricter in some splits (table 1).")
        w("- **Probe share ρ** trades risk for fewer asks in the refund domain (a smaller ρ leaves more budget for the "
          "post-probe stage); in the Kubernetes domain the effect is small.")
        w(f"\n**Latency.** Gate overhead with a trivial model: {A['overhead_ms']['p50']:.2f} ms median, "
          f"{A['overhead_ms']['p95']:.2f} ms p95. Per check with the domain models: "
          + ", ".join(f"{A[d]['latency_ms']['p50']:.1f} ms ({SHORT[d]})" for d in doms if d in A)
          + " (median). The reactor twin takes about 0.1 s per uncached check.\n")

    w("## 6. Caveats\n")
    w("- Simulated domains and scripted agents; real-LLM agents and a public benchmark domain are future work.")
    w("- The guarantee is marginal (over episodes) and, by default, in expectation over calibration sets.")
    w("- Validity requires exchangeability; the end-to-end tutorial shows a drift that the input-based monitor detected "
      "only after 227 decisions, during which the unsafe rate exceeded α.")
    w("- Labels are counterfactual (available for every candidate) because the domains are simulated.\n")
    w("## Reproduce\n")
    w("```bash\ncd examples\nPYTHONPATH=.. python run_examples.py       # all domains (the reactor takes ~20 min)\n"
      "PYTHONPATH=.. python ablations.py\npython report.py                          # regenerates this page\n```")
    ASSETS.mkdir(parents=True, exist_ok=True)
    for png in ("methods_all_domains.png", "alpha_sweep_all_domains.png", "validity_resplits.png"):
        if (RES / png).exists():
            shutil.copy(RES / png, ASSETS / png)
    OUT.write_text("\n".join(L) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
